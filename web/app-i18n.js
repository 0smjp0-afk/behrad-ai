/* زبانِ جاری: S.locale اگر هست، وگرنه fa */
function curLocale() {
  try { return (typeof S !== 'undefined' && S.locale === 'en') ? 'en' : 'fa'; } catch { return 'fa'; }
}
/* t('key', ...args) — جای‌نگهدارهای %1..%N با args پر می‌شوند */
function t(key, ...args) {
  const e = I18N[key];
  if (!e) return key;
  const lang = curLocale();
  let s = e[lang] != null && e[lang] !== '' ? e[lang] : e.fa;
  if (args.length) s = s.replace(/%(\\d+)/g, (m, d) => { const i = +d - 1; return i >= 0 && i < args.length && args[i] != null ? String(args[i]) : ''; });
  return s;
}
/* زبانِ راست‌به‌چپ است؟ */
function isRTL() { return curLocale() === 'fa'; }
/* اعمالِ زبان روی <html> (lang/dir) — بعد از هر تغییرِ زبان صدا زده می‌شود */
function applyLocale() {
  const lang = curLocale();
  const root = document.documentElement;
  root.setAttribute('lang', lang);
  root.setAttribute('dir', lang === 'fa' ? 'rtl' : 'ltr');
  root.setAttribute('data-locale', lang);
}

